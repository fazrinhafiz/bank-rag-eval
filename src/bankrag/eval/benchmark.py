"""Compare retrieval modes on equal terms: each mode gets its own threshold calibrated on dev, then is
scored on test. Retrieval-only metrics are also reported on all answerable items (dev + test), since
ranking has no fitted parameters and more items narrow the error bars."""
from __future__ import annotations

from ..config import resolve, with_overrides
from ..pipeline import Pipeline
from ..retrieval import MODES
from . import metrics as M
from .calibrate import calibrate
from .harness import load_golden, run_eval


def run_benchmark(cfg: dict) -> list[dict]:
    golden = resolve(cfg, "golden_set")
    dev, everything = load_golden(golden, "dev"), load_golden(golden, "all")
    rows = []
    for mode in MODES:
        mcfg = with_overrides(cfg, **{"retrieval.mode": mode})
        pipe = Pipeline(mcfg)
        cal = calibrate(dev, pipe.retriever, pipe.top_k)
        pipe.threshold = cal.threshold
        tcfg = with_overrides(mcfg, abstain_threshold=cal.threshold)
        dev_run = run_eval(tcfg, "dev", pipeline=pipe)
        run = run_eval(tcfg, "test", pipeline=pipe)

        retr, lat = [], []
        for item in everything:
            if item["category"] not in ("answerable", "pii"):
                continue
            resp = pipe.ask(item["question"])
            retr.append(resp.retrieved_docs)
            lat.append(resp.trace["latency_ms"].get("retrieval", 0.0))
        exp = [i["expected_doc"] for i in everything if i["category"] in ("answerable", "pii")]
        n = len(exp)
        rows.append({
            "mode": mode,
            "threshold": cal.threshold,
            "all_hit_at_1": sum(M.hit_at_k(d, e, 1) for d, e in zip(retr, exp)) / n,
            "all_hit_at_3": sum(M.hit_at_k(d, e, 3) for d, e in zip(retr, exp)) / n,
            "all_mrr": sum(M.reciprocal_rank(d, e) for d, e in zip(retr, exp)) / n,
            "n_retrieval_items": n,
            "retrieval_p50_ms": M.percentile(lat, 50),
            "dev_abstention_f1": cal.best.f1,
            "dev_key_fact_recall": dev_run.metrics["key_fact_recall"],
            **{f"test_{k}": run.metrics[k] for k in ("key_fact_recall", "abstention_precision", "abstention_recall",
                                                    "abstention_f1", "confidence_auroc", "task_success")},
        })
    return rows


SIMPLICITY = {"bm25": 0, "tfidf": 1, "hybrid": 2}


def select_mode(rows: list[dict]) -> str:
    """Model selection uses DEV metrics only: best dev abstention F1, then dev key-fact recall, then the
    simpler mode. Test columns are reported but never used to choose."""
    return max(rows, key=lambda r: (round(r["dev_abstention_f1"], 6), round(r["dev_key_fact_recall"], 6), -SIMPLICITY[r["mode"]]))["mode"]


def benchmark_markdown(rows: list[dict], cfg: dict) -> str:
    pct = lambda x: f"{x:.1%}"
    lines = [
        "# Retrieval benchmark: BM25 vs TF-IDF vs hybrid (RRF)",
        "",
        "Generated by `python -m bankrag benchmark`. Same golden set, same offline generator, same guardrails;",
        "only the retrieval mode changes. Each mode's abstain threshold is calibrated on the **dev** split and",
        "the end-to-end columns are measured on the **test** split. Retrieval columns use all "
        f"{rows[0]['n_retrieval_items']} answerable + PII items (ranking has no fitted parameters).",
        "",
        f"**Selected on dev: `{select_mode(rows)}`** (rule: best dev abstention F1, then dev key-fact recall, then the simpler mode).",
        "",
        "| mode | dev abstain F1 | dev key-fact recall | hit@1 (all) | hit@3 (all) | MRR (all) | threshold (dev) | key-fact recall (test) | abstain P (test) | abstain R (test) | abstain F1 (test) | conf. AUROC (test) | task success (test) | retrieval p50 |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['mode']} | {r['dev_abstention_f1']:.3f} | {pct(r['dev_key_fact_recall'])} | {pct(r['all_hit_at_1'])} | {pct(r['all_hit_at_3'])} | {r['all_mrr']:.3f} | {r['threshold']:.3f} | "
            f"{pct(r['test_key_fact_recall'])} | {pct(r['test_abstention_precision'])} | {pct(r['test_abstention_recall'])} | "
            f"{r['test_abstention_f1']:.3f} | {r['test_confidence_auroc']:.3f} | {pct(r['test_task_success'])} | {r['retrieval_p50_ms']:.2f} ms |")
    lines += ["", "Latency is wall-clock on the machine that ran the benchmark and varies run to run; all other columns are deterministic.", ""]
    return "\n".join(lines)
